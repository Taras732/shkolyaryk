/** Усі слова букви: основне + додаткові. */
export function wordsOf(l: Letter): { word: string; emoji: string }[] {
  return [{ word: l.word, emoji: l.emoji }, ...(MORE[l.ch] ?? []).map(([word, emoji]) => ({ word, emoji }))];
}

/** Та сама буква з випадковим словом-картинкою (для питань). */
export function withRandomWord(l: Letter, rng: () => number = Math.random): Letter {
  if (!l.initial) return l;
  const all = wordsOf(l);
  const w = all[Math.floor(rng() * all.length)];
  return { ...l, word: w.word, emoji: w.emoji };
}
