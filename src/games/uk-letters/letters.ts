/** Ключі аудіофайлів: слово-опора і фраза-знайомство з буквою. */
export const wordKey = (l: Letter) => `w_${l.word}`;
export const introKey = (l: Letter) => `l_${l.ch}`;
export const introText = (l: Letter) => (l.initial ? `${l.word}. ${l.word}` : `${l.word}`);
