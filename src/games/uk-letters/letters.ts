/**
 * Букви в порядку букваря (спершу голосні й сонорні — з них раніше складаються
 * склади), кожна з опорним словом-картинкою, що ПОЧИНАЄТЬСЯ з її звуку.
 * Виняток — И (українські слова з неї не починаються) та Ь (звуку не має):
 * для них опорне слово, де буква стоїть усередині чи в кінці.
 */
export interface Letter {
  ch: string;
  word: string;
  emoji: string;
  /** Звук на початку слова — для гри «з якої букви починається». false — лише показ. */
  initial: boolean;
}

const L = (ch: string, word: string, emoji: string, initial = true): Letter => ({ ch, word, emoji, initial });

